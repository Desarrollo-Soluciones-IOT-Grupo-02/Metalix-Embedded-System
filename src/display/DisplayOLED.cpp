DisplayOLED::DisplayOLED(int width, int height)
: oled(width, height, &Wire, -1) {}

bool DisplayOLED::begin() {
    Wire.begin(21, 22);
    return oled.begin(SSD1306_SWITCHCAPVCC, 0x3C);
}

void DisplayOLED::showLogo() {
    oled.clearDisplay();
    oled.drawBitmap(0, 0, metalix_logo, 128, 64, SSD1306_WHITE);
    oled.display();
}

void DisplayOLED::showMessage(const String& msg) {
    oled.clearDisplay();
    oled.setTextSize(2);
    oled.setTextColor(SSD1306_WHITE);
    oled.setCursor(0, 20);
    oled.println(msg);
    oled.display();
}

void DisplayOLED::showWelcome() {
    oled.clearDisplay();
    oled.setTextSize(1);
    oled.setTextColor(SSD1306_WHITE);
    oled.setCursor(5, 15);
    oled.println("  Ingrese un");
    oled.setCursor(5, 30);
    oled.println(" metal para");
    oled.setCursor(5, 45);
    oled.println("   iniciar");
    oled.display();
}

void DisplayOLED::showPoints(int points) {
    oled.clearDisplay();
    oled.setTextSize(1);
    oled.setTextColor(SSD1306_WHITE);
    
    oled.setCursor(25, 5);
    oled.println("PUNTOS:");
    
    oled.setTextSize(3);
    oled.setCursor(45, 25);
    oled.println(points);
    
    oled.setTextSize(1);
    oled.setCursor(10, 55);
    oled.println("Siga insertando");
    
    oled.display();
}

